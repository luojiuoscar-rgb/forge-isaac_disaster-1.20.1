"""Convert the approved Blockbench OBJ and embedded PNGs into runtime assets.

Requires Python 3 + Pillow. Run from any directory; --check validates without writing.
"""
import argparse
import base64
import hashlib
import io
import json
import math
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PACKAGE = "net.luojiuoscar.isaac_disaster.client.model.familiar.mom_knife"
MESH = ROOT / "src/main/java" / Path(*PACKAGE.split(".")) / "MomKnifeMesh.java"
ATLAS = ROOT / "src/main/resources/assets/isaac_disaster/textures/entity/familiar/mom_knife.png"
TAIL_X, TAIL_Y = -1.0, -6.5
REGIONS = {
    "mom_knife_blade_silver": (0, 0, 32, 64),
    "mom_knife_handle_dark": (32, 0, 16, 16),
    "mom_knife_handle_wood": (48, 0, 16, 16),
}

def generate():
    source = (HERE / "mom_knife.bbmodel").read_bytes()
    obj = (HERE / "mom_knife.obj").read_bytes()
    atlas = Image.new("RGBA", (64, 64))
    materials = {}
    for texture in json.loads(source)["textures"]:
        if texture["name"] not in REGIONS:
            continue
        x, y, width, height = REGIONS[texture["name"]]
        image = Image.open(io.BytesIO(base64.b64decode(texture["source"].split(",", 1)[1]))).convert("RGBA")
        if image.size != (width, height):
            raise ValueError(f"Unexpected texture size: {texture['name']} {image.size}")
        atlas.paste(image, (x, y))
        materials["m_" + texture["uuid"]] = (x, y, width, height)
    if len(materials) != len(REGIONS):
        raise ValueError("Missing approved blade/handle texture")
    positions, uvs, normals, quads = [], [], [], []
    material = None
    for line in obj.decode("utf-8").splitlines():
        parts = line.split()
        if not parts:
            continue
        kind, *args = parts
        if kind == "v":
            x, y, z = (float(value) * 16 for value in args)
            positions.append((x - TAIL_X, -(y - TAIL_Y), -z))
        elif kind == "vt":
            uvs.append(tuple(map(float, args)))
        elif kind == "vn":
            x, y, z = map(float, args)
            normals.append((x, -y, -z))
        elif kind == "usemtl":
            material = materials[args[0]]
        elif kind == "f":
            if len(args) != 4 or material is None:
                raise ValueError("The runtime mesh requires textured quads")
            ox, oy, width, height = material
            values, face_normals, points = [], [], []
            for corner in args:
                pi, ti, ni = (int(value) - 1 for value in corner.split("/"))
                point, (u, v), normal = positions[pi], uvs[ti], normals[ni]
                u, v = (ox + u * width) / 64, (oy + (1 - v) * height) / 64
                if not (0 <= u <= 1 and 0 <= v <= 1):
                    raise ValueError("UV outside atlas")
                values.extend((*point, u, v))
                face_normals.append(normal)
                points.append(point)
            normal = face_normals[0]
            if any(n != normal for n in face_normals) or not math.isclose(sum(v*v for v in normal), 1, abs_tol=1e-6):
                raise ValueError("Expected a unit face normal")
            a, b, c = points[:3]
            ab, ac = [b[i]-a[i] for i in range(3)], [c[i]-a[i] for i in range(3)]
            cross = (ab[1]*ac[2]-ab[2]*ac[1], ab[2]*ac[0]-ab[0]*ac[2], ab[0]*ac[1]-ab[1]*ac[0])
            if sum(cross[i]*normal[i] for i in range(3)) <= 0:
                raise ValueError("Inverted or degenerate OBJ face")
            quads.append(values + list(normal))
    if len(quads) != 46:
        raise ValueError(f"Expected approved 46-quad mesh, got {len(quads)}")
    length = -min(p[1] for p in positions)
    if not math.isclose(length, 26.5):
        raise ValueError("Unexpected approved model length")
    def number(value):
        text = f"{value:.8f}".rstrip("0").rstrip(".")
        return ("0" if text in ("", "-0") else text) + "F"
    rows = ",\n".join("        {" + ", ".join(map(number, q)) + "}" for q in quads)
    java = f"""package {PACKAGE};

// Generated by blockbench/familiar/mom_knife/generate_runtime.py. Do not edit.
// bbmodel SHA256: {hashlib.sha256(source).hexdigest()}
// OBJ SHA256: {hashlib.sha256(obj).hexdigest()}
final class MomKnifeMesh {{
    static final float LENGTH = {number(length)};
    // Four vertices (x, y, z, u, v), then the face normal (x, y, z).
    static final float[][] QUADS = {{
{rows}
    }};
    private MomKnifeMesh() {{
    }}
}}
""".encode("utf-8")
    png = io.BytesIO()
    atlas.save(png, format="PNG")
    return {MESH: java, ATLAS: png.getvalue()}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in generate().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"STALE: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"{'OK' if args.check else 'WROTE'}: {path.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
